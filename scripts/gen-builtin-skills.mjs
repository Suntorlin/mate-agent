#!/usr/bin/env node
// Regenerate the control plane's copy of the skills baked into the sandbox image, which the
// Skills page lists and shows. Run after changing anything under skills/builtin/:
//
//   node scripts/gen-builtin-skills.mjs
//
// builtin-skills.test.ts fails while the copy is stale.

import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const skillsDir = join(root, "skills/builtin");
const output = join(root, "packages/control-plane/src/skills/builtin-skills.generated.ts");

function walk(dir) {
  return readdirSync(dir)
    .filter((name) => name !== ".DS_Store" && name !== "__pycache__" && name !== "node_modules")
    .sort()
    .flatMap((name) => {
      const path = join(dir, name);
      return statSync(path).isDirectory() ? walk(path) : [path];
    });
}

/** The `description` of a SKILL.md frontmatter, folded onto one line. */
function frontmatterDescription(markdown) {
  const lines = markdown.split("\n");
  const end = lines.indexOf("---", 1);
  const start = lines.findIndex((line, index) => index < end && line.startsWith("description:"));
  if (start === -1) throw new Error("SKILL.md has no description");
  const parts = [lines[start].slice("description:".length).trim()];
  for (let index = start + 1; index < end && /^\s+\S/.test(lines[index]); index++) {
    parts.push(lines[index].trim());
  }
  return parts.filter(Boolean).join(" ");
}

export function buildBuiltinSkills() {
  return readdirSync(skillsDir)
    .filter((name) => statSync(join(skillsDir, name, "SKILL.md"), { throwIfNoEntry: false }))
    .sort()
    .map((name) => {
      const dir = join(skillsDir, name);
      const markdown = readFileSync(join(dir, "SKILL.md"), "utf8");
      return {
        name,
        description: frontmatterDescription(markdown),
        markdown,
        files: walk(dir)
          .map((path) => ({ path: relative(dir, path), sizeBytes: statSync(path).size }))
          .filter((file) => file.path !== "SKILL.md"),
      };
    });
}

export function renderBuiltinSkills(skills) {
  return `// Generated by scripts/gen-builtin-skills.mjs from skills/builtin/. Do not edit.

export interface BuiltinSkillSource {
  name: string;
  description: string;
  markdown: string;
  files: { path: string; sizeBytes: number }[];
}

export const BUILTIN_SKILL_SOURCES: readonly BuiltinSkillSource[] = ${JSON.stringify(skills, null, 2)};
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(output, renderBuiltinSkills(buildBuiltinSkills()));
  console.log(`wrote ${relative(root, output)}`);
}
